package main

import (
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"os"
	"path/filepath"
	"strconv"
	"strings"

	"github.com/alexflint/go-arg"
)

type arguments struct {
	Output string `arg:"-o,--output" default:"contract_gen.go" help:"generated Go file path"`
}

func main() {
	var args arguments
	arg.MustParse(&args)

	var (
		files []string
		err   error
	)

	if files, err = filepath.Glob("*.go"); err != nil {
		fail(err)
	}

	var (
		contracts []contract
		file      *ast.File
		fileSet   *token.FileSet = token.NewFileSet()
	)

	for _, path := range files {
		if strings.HasSuffix(path, "_test.go") || path == args.Output || strings.HasSuffix(path, "_gen.go") {
			continue
		}

		if file, err = parser.ParseFile(fileSet, path, nil, 0); err != nil {
			fail(err)
		}

		for _, declaration := range file.Decls {
			var (
				general *ast.GenDecl
				ok      bool
			)

			if general, ok = declaration.(*ast.GenDecl); !ok || general.Tok != token.TYPE {
				continue
			}

			for _, specification := range general.Specs {
				var (
					typeSpec *ast.TypeSpec
					ok       bool
				)

				if typeSpec, ok = specification.(*ast.TypeSpec); !ok {
					continue
				}

				var interfaceType *ast.InterfaceType
				if interfaceType, ok = typeSpec.Type.(*ast.InterfaceType); !ok {
					continue
				}

				var (
					found        bool
					contractInfo contract
				)

				if contractInfo, found = parseContract(typeSpec.Name.Name, interfaceType); found {
					contracts = append(contracts, contractInfo)
				}
			}
		}
	}

	if len(files) == 0 {
		fail(fmt.Errorf("no Go files found in current directory"))
	}

	if len(contracts) == 0 {
		fail(fmt.Errorf("no marked contract interfaces found"))
	}

	var contractTypes map[string]string = map[string]string{}
	for _, contractInfo := range contracts {
		contractTypes[contractInfo.name] = contractInfo.generatedName
	}

	for contractIndex := range contracts {
		for methodIndex := range contracts[contractIndex].methods {
			contracts[contractIndex].methods[methodIndex].messageType = "ContractMessage" + contracts[contractIndex].generatedName + contracts[contractIndex].methods[methodIndex].name
		}

		for streamIndex := range contracts[contractIndex].streams {
			var nestedDefinition string = contracts[contractIndex].streams[streamIndex].nestedDefinition
			if nestedDefinition == "" {
				continue
			}

			var (
				nestedName string
				exists     bool
			)

			if nestedName, exists = contractTypes[nestedDefinition]; !exists {
				fail(fmt.Errorf("stream option references unmarked contract %s", nestedDefinition))
			}

			contracts[contractIndex].streams[streamIndex].nestedContract = nestedName
			for methodIndex := range contracts[contractIndex].methods {
				if contracts[contractIndex].methods[methodIndex].name == contracts[contractIndex].streams[streamIndex].method {
					contracts[contractIndex].methods[methodIndex].nestedContract = nestedName
				}
			}
		}
	}

	var source strings.Builder
	fmt.Fprintf(&source, `// Code generated by arcticgen; DO NOT EDIT.

package %s

import (
	"context"

	"github.com/z46-dev/arctic"
)

`, file.Name.Name)
	fmt.Fprintf(&source, "type ContractMessageType = arctic.ContractMessageType\n\nconst (\n")
	var firstMessageType bool = true
	for _, contractInfo := range contracts {
		for _, method := range contractInfo.methods {
			if firstMessageType {
				fmt.Fprintf(&source, "\t%s ContractMessageType = iota\n", method.messageType)
				firstMessageType = false
			} else {
				fmt.Fprintf(&source, "\t%s\n", method.messageType)
			}
		}
	}

	fmt.Fprintf(&source, ")\n")
	var generatedNames map[string]struct{} = map[string]struct{}{}
	for _, contractInfo := range contracts {
		var generatedName string = contractInfo.generatedName
		if _, exists := generatedNames[generatedName]; exists {
			fail(fmt.Errorf("multiple definitions generate contract type %s", generatedName))
		}
		
		generatedNames[generatedName] = struct{}{}

		fmt.Fprintf(&source, `
type %s struct {
	peer *arctic.ContractPeer
	scopeID uint64
}

	type %sOptions struct {
`, generatedName, generatedName)

		for _, option := range contractInfo.options {
			fmt.Fprintf(&source, "\t%s %s %s\n", option.name, option.typeName, option.tag)
		}

		fmt.Fprintf(&source, `}

func %sFor() (factory arctic.ContractFactory[%s]) {
    factory = func(peer *arctic.ContractPeer) (contract %s) {
        contract.peer = peer
        return
    }
    return
}

func (contract %s) AddInboundMiddleware(middleware arctic.ContractMiddleware) {
	contract.peer.AddInboundMiddleware(middleware)
}

func (contract %s) AddOutboundMiddleware(middleware arctic.ContractMiddleware) {
	contract.peer.AddOutboundMiddleware(middleware)
}
		`, generatedName, generatedName, generatedName, generatedName, generatedName)
		for _, method := range contractInfo.methods {
			if method.streaming {
				var contextName string = method.name + "Context"
				if method.nestedContract != "" {
					fmt.Fprintf(&source, `
type %s struct {
	*arctic.ContractContext
	Stream %s
}

func (contract %s) New%sContext(parent context.Context) (streamContext *%s) {
	var base *arctic.ContractContext = arctic.NewContractStreamingContext(parent, contract.peer, contract.scopeID)
	var nestedContract %s = %s{peer: contract.peer, scopeID: base.ScopeID()}
	streamContext = &%s{ContractContext: base, Stream: nestedContract}
	return
}

func (contract %s) %s(ctx *%s, request %s) (response %s, err error) {
	return arctic.ContractStreamingCallTyped[%s, %s](ctx.ContractContext, %s, %q, request)
}

func (contract %s) On%s(handler func(*%s, %s) %s) {
	arctic.ContractStreamingHandleTypedScoped[%s, %s](contract.peer, contract.scopeID, %s, %q, func(ctx *arctic.ContractContext, request %s) %s {
		var nestedContract %s = %s{peer: contract.peer, scopeID: ctx.ScopeID()}
		var streamContext *%s = &%s{ContractContext: ctx, Stream: nestedContract}
		return handler(streamContext, request)
	})
}
`,
						contextName, method.nestedContract,
						generatedName, method.name, contextName,
						method.nestedContract, method.nestedContract,
						contextName,
						generatedName, method.name, contextName, method.request, method.response, method.request, method.response, method.messageType, generatedName+"."+method.name,
						generatedName, method.name, contextName, method.request, method.response,
						method.request, method.response, method.messageType, generatedName+"."+method.name, method.request, method.response,
						method.nestedContract, method.nestedContract, contextName, contextName)
					continue
				}

				var streamName string = method.name + "Stream"
				fmt.Fprintf(&source, `
type %s struct {
	*arctic.ContractContext
	Stream %s
}

type %s struct {
	context *arctic.ContractContext
}

func (contract %s) New%sContext(parent context.Context) (streamContext *%s) {
	var base *arctic.ContractContext = arctic.NewContractStreamingContext(parent, contract.peer, contract.scopeID)
	streamContext = &%s{ContractContext: base, Stream: %s{context: base}}
	return
}
`, contextName, streamName, streamName, generatedName, method.name, contextName, contextName, streamName)

				fmt.Fprintf(&source, `
func (stream %s) SendRequest(message %s) (err error) {
	return arctic.SendContractStreamData(stream.context, "request", message)
}

func (stream %s) OnRequest(handler func(%s)) {
	arctic.OnContractStreamData(stream.context, "request", handler)
}

func (stream %s) SendResponse(message %s) (err error) {
	return arctic.SendContractStreamData(stream.context, "response", message)
}

func (stream %s) OnResponse(handler func(%s)) {
	arctic.OnContractStreamData(stream.context, "response", handler)
}
`, streamName, method.requestBody, streamName, method.requestBody, streamName, method.responseBody, streamName, method.responseBody)

				fmt.Fprintf(&source, `
func (contract %s) %s(ctx *%s, request %s) (response %s, err error) {
	return arctic.ContractStreamingCallTyped[%s, %s](ctx.ContractContext, %s, %q, request)
}

func (contract %s) On%s(handler func(*%s, %s) %s) {
	arctic.ContractStreamingHandleTypedScoped[%s, %s](contract.peer, contract.scopeID, %s, %q, func(ctx *arctic.ContractContext, request %s) %s {
		var streamContext *%s = &%s{ContractContext: ctx, Stream: %s{context: ctx}}
		return handler(streamContext, request)
	})
}
				`, generatedName, method.name, contextName, method.request, method.response, method.request, method.response, method.messageType, generatedName+"."+method.name,
					generatedName, method.name, contextName, method.request, method.response, method.request, method.response, method.messageType, generatedName+"."+method.name,
					method.request, method.response, contextName, contextName, streamName)
				continue
			}

			fmt.Fprintf(&source, `
func (contract %s) %s(ctx context.Context, request %s) (response %s, err error) {
	return arctic.ContractCallTypedScoped[%s, %s](ctx, contract.peer, contract.scopeID, %s, %q, request)
}

func (contract %s) On%s(handler func(*arctic.ContractContext, %s) %s) {
	arctic.ContractHandleTypedScoped[%s, %s](contract.peer, contract.scopeID, %s, %q, handler)
}
			`, generatedName, method.name, method.request, method.response, method.request, method.response, method.messageType, generatedName+"."+method.name, generatedName, method.name, method.request, method.response, method.request, method.response, method.messageType, generatedName+"."+method.name)
		}
	}

	var formatted []byte
	if formatted, err = format.Source([]byte(source.String())); err != nil {
		fail(err)
	}

	if err = os.WriteFile(args.Output, formatted, 0600); err != nil {
		fail(err)
	}
}

type (
	contract struct {
		name          string
		generatedName string
		options       []contractOption
		methods       []contractMethod
		streams       []contractStream
	}

	contractMethod struct {
		name             string
		messageType      string
		request          string
		response         string
		streaming        bool
		requestBody      string
		responseBody     string
		nestedDefinition string
		nestedContract   string
	}

	contractOption struct {
		name     string
		typeName string
		tag      string
	}

	contractStream struct {
		method           string
		requestBody      string
		responseBody     string
		nestedDefinition string
		nestedContract   string
	}
)

// parseContract extracts contract methods and options from a marked interface.
func parseContract(name string, interfaceType *ast.InterfaceType) (result contract, found bool) {
	result.name = name
	result.generatedName = strings.TrimSuffix(name, "Definition")
	if result.generatedName == name {
		result.generatedName += "Contract"
	}

	for _, field := range interfaceType.Methods.List {
		if len(field.Names) == 0 {
			continue
		}

		var (
			methodType *ast.FuncType
			ok         bool
		)

		if methodType, ok = field.Type.(*ast.FuncType); !ok {
			continue
		}

		if field.Names[0].Name == "__ArcticContract__" {
			if methodType.Params == nil || len(methodType.Params.List) != 0 || methodType.Results == nil || len(methodType.Results.List) != 1 {
				continue
			}

			var options *ast.StructType
			if options, ok = methodType.Results.List[0].Type.(*ast.StructType); !ok {
				continue
			}

			found = true
			for _, optionField := range options.Fields.List {
				var typeName strings.Builder
				if err := format.Node(&typeName, token.NewFileSet(), optionField.Type); err != nil {
					continue
				}

				var tag string
				if optionField.Tag != nil {
					tag = optionField.Tag.Value
				}

				for _, fieldName := range optionField.Names {
					result.options = append(result.options, contractOption{
						name:     fieldName.Name,
						typeName: typeName.String(),
						tag:      tag,
					})

					if optionField.Tag != nil {
						var (
							optionTag string
							err       error
						)

						if optionTag, err = strconv.Unquote(optionField.Tag.Value); err != nil || !strings.Contains(optionTag, "streaming") {
							continue
						}

						var streamInfo contractStream = contractStream{method: fieldName.Name}
						switch streamOptions := optionField.Type.(type) {
						case *ast.Ident:
							streamInfo.nestedDefinition = streamOptions.Name
						case *ast.StructType:
							for _, streamField := range streamOptions.Fields.List {
								if streamField.Tag == nil {
									continue
								}

								var streamTag string
								if streamTag, err = strconv.Unquote(streamField.Tag.Value); err != nil {
									continue
								}

								var streamType strings.Builder
								if err = format.Node(&streamType, token.NewFileSet(), streamField.Type); err != nil {
									continue
								}

								if strings.Contains(streamTag, "streaming.request") {
									streamInfo.requestBody = streamType.String()
								} else if strings.Contains(streamTag, "streaming.response") {
									streamInfo.responseBody = streamType.String()
								}
							}
						}

						result.streams = append(result.streams, streamInfo)
					}
				}
			}

			continue
		}

		if methodType.Params == nil || len(methodType.Params.List) != 1 || methodType.Results == nil || len(methodType.Results.List) != 1 {
			continue
		}

		var (
			request strings.Builder
			err     error
		)

		if err = format.Node(&request, token.NewFileSet(), methodType.Params.List[0].Type); err != nil {
			continue
		}

		var response strings.Builder
		if err = format.Node(&response, token.NewFileSet(), methodType.Results.List[0].Type); err != nil {
			continue
		}

		result.methods = append(result.methods, contractMethod{
			name: field.Names[0].Name, request: request.String(), response: response.String(),
		})
	}

	for _, streamInfo := range result.streams {
		var found bool
		for methodIndex := range result.methods {
			if result.methods[methodIndex].name == streamInfo.method {
				found = true
				if streamInfo.nestedDefinition == "" && (streamInfo.requestBody == "" || streamInfo.responseBody == "") {
					fail(fmt.Errorf("streaming method %s must declare streaming.request and streaming.response body types", streamInfo.method))
				}

				result.methods[methodIndex].streaming = true
				result.methods[methodIndex].requestBody = streamInfo.requestBody
				result.methods[methodIndex].responseBody = streamInfo.responseBody
				result.methods[methodIndex].nestedDefinition = streamInfo.nestedDefinition
				break
			}
		}

		if !found {
			fail(fmt.Errorf("stream options reference unknown contract method %s", streamInfo.method))
		}
	}

	return
}

func fail(err error) {
	fmt.Fprintln(os.Stderr, err)
	os.Exit(1)
}
