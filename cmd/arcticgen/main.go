package main

import (
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"os"
	"path/filepath"
	"strings"

	"github.com/alexflint/go-arg"
)

type arguments struct {
	Output string `arg:"-o,--output" default:"contract_gen.go" help:"generated Go file path"`
}

func main() {
	var args arguments
	arg.MustParse(&args)

	var (
		files []string
		err   error
	)

	if files, err = filepath.Glob("*.go"); err != nil {
		fail(err)
	}

	var (
		contracts []contract
		file      *ast.File
		fileSet   *token.FileSet = token.NewFileSet()
	)

	for _, path := range files {
		if strings.HasSuffix(path, "_test.go") || path == args.Output || strings.HasSuffix(path, "_gen.go") {
			continue
		}

		if file, err = parser.ParseFile(fileSet, path, nil, 0); err != nil {
			fail(err)
		}

		for _, declaration := range file.Decls {
			var (
				general *ast.GenDecl
				ok      bool
			)

			if general, ok = declaration.(*ast.GenDecl); !ok || general.Tok != token.TYPE {
				continue
			}

			for _, specification := range general.Specs {
				var (
					typeSpec *ast.TypeSpec
					ok       bool
				)

				if typeSpec, ok = specification.(*ast.TypeSpec); !ok {
					continue
				}

				var interfaceType *ast.InterfaceType
				if interfaceType, ok = typeSpec.Type.(*ast.InterfaceType); !ok {
					continue
				}

				var (
					found        bool
					contractInfo contract
				)

				if contractInfo, found = parseContract(typeSpec.Name.Name, interfaceType); found {
					contracts = append(contracts, contractInfo)
				}
			}
		}
	}

	if len(files) == 0 {
		fail(fmt.Errorf("no Go files found in current directory"))
	}

	if len(contracts) == 0 {
		fail(fmt.Errorf("no marked contract interfaces found"))
	}

	var source strings.Builder
	fmt.Fprintf(&source, `// Code generated by arcticgen; DO NOT EDIT.

package %s

import (
	"context"
	"github.com/z46-dev/arctic"
)

`, file.Name.Name)
	var generatedNames map[string]struct{} = map[string]struct{}{}
	for _, contractInfo := range contracts {
		var generatedName string = contractInfo.generatedName
		if _, exists := generatedNames[generatedName]; exists {
			fail(fmt.Errorf("multiple definitions generate contract type %s", generatedName))
		}
		generatedNames[generatedName] = struct{}{}

		fmt.Fprintf(&source, `
type %s struct {
	peer *arctic.ContractPeer
}

	type %sOptions struct {
`, generatedName, generatedName)

		for _, option := range contractInfo.options {
			fmt.Fprintf(&source, "\t%s %s %s\n", option.name, option.typeName, option.tag)
		}

		fmt.Fprintf(&source, `}

func %sFor() (factory arctic.ContractFactory[%s]) {
    factory = func(peer *arctic.ContractPeer) (contract %s) {
        contract.peer = peer
        return
    }
    return
}
		`, generatedName, generatedName, generatedName)
		for _, method := range contractInfo.methods {
			fmt.Fprintf(&source, `
func (contract %s) %s(ctx context.Context, request %s) (response %s, err error) {
	return arctic.ContractCall[%s, %s](ctx, contract.peer, %q, request)
}

func (contract %s) On%s(handler func(*arctic.ContractContext, %s) %s) {
	arctic.ContractHandle[%s, %s](contract.peer, %q, handler)
}
			`, generatedName, method.name, method.request, method.response, method.request, method.response, generatedName+"."+method.name, generatedName, method.name, method.request, method.response, method.request, method.response, generatedName+"."+method.name)
		}
	}

	var formatted []byte
	if formatted, err = format.Source([]byte(source.String())); err != nil {
		fail(err)
	}

	if err = os.WriteFile(args.Output, formatted, 0600); err != nil {
		fail(err)
	}
}

type (
	contract struct {
		name          string
		generatedName string
		options       []contractOption
		methods       []contractMethod
	}

	contractMethod struct {
		name     string
		request  string
		response string
	}

	contractOption struct {
		name     string
		typeName string
		tag      string
	}
)

// parseContract extracts contract methods and options from a marked interface.
func parseContract(name string, interfaceType *ast.InterfaceType) (result contract, found bool) {
	result.name = name
	result.generatedName = strings.TrimSuffix(name, "Definition")
	if result.generatedName == name {
		result.generatedName += "Contract"
	}
	for _, field := range interfaceType.Methods.List {
		if len(field.Names) == 0 {
			continue
		}

		var (
			methodType *ast.FuncType
			ok         bool
		)

		if methodType, ok = field.Type.(*ast.FuncType); !ok {
			continue
		}

		if field.Names[0].Name == "__ArcticContract__" {
			if methodType.Params == nil || len(methodType.Params.List) != 0 || methodType.Results == nil || len(methodType.Results.List) != 1 {
				continue
			}

			var options *ast.StructType
			if options, ok = methodType.Results.List[0].Type.(*ast.StructType); !ok {
				continue
			}

			found = true
			for _, optionField := range options.Fields.List {
				var typeName strings.Builder
				if err := format.Node(&typeName, token.NewFileSet(), optionField.Type); err != nil {
					continue
				}

				var tag string
				if optionField.Tag != nil {
					tag = optionField.Tag.Value
				}

				for _, fieldName := range optionField.Names {
					result.options = append(result.options, contractOption{
						name:     fieldName.Name,
						typeName: typeName.String(),
						tag:      tag,
					})
				}
			}

			continue
		}

		if methodType.Params == nil || len(methodType.Params.List) != 1 || methodType.Results == nil || len(methodType.Results.List) != 1 {
			continue
		}

		var (
			request strings.Builder
			err     error
		)

		if err = format.Node(&request, token.NewFileSet(), methodType.Params.List[0].Type); err != nil {
			continue
		}

		var response strings.Builder
		if err = format.Node(&response, token.NewFileSet(), methodType.Results.List[0].Type); err != nil {
			continue
		}

		result.methods = append(result.methods, contractMethod{
			name: field.Names[0].Name, request: request.String(), response: response.String(),
		})
	}

	return
}

func fail(err error) {
	fmt.Fprintln(os.Stderr, err)
	os.Exit(1)
}
